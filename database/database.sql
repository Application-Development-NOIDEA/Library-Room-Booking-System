-- A. USERS
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    student_id VARCHAR(50) UNIQUE,
    role VARCHAR(20) NOT NULL DEFAULT 'student'
        CHECK (role IN ('student', 'staff', 'admin')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- B. ROOMS
CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code VARCHAR(50) UNIQUE NOT NULL,
    room_name VARCHAR(150) NOT NULL,
    room_type VARCHAR(50) NOT NULL,
    capacity INTEGER NOT NULL,
    location VARCHAR(150),
    facilities JSONB,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'maintenance'))
);

-- C. BOOKINGS
CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'confirmed'
        CHECK (status IN (
            'held', 'confirmed', 'checked_in',
            'checked_out', 'cancelled', 'no_show'
        )),
    qr_token_hash VARCHAR(255),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CHECK (end_at > start_at)
);

-- D. BOOKING CHECKINS
CREATE TABLE booking_checkins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    checked_in_at TIMESTAMPTZ,
    checked_in_by BIGINT REFERENCES users(id),
    checked_out_at TIMESTAMPTZ,
    checked_out_by BIGINT REFERENCES users(id)
);

-- E. WAITING LIST ENTRIES
CREATE TABLE waiting_list_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    room_type VARCHAR(50) NOT NULL,
    room_id BIGINT REFERENCES rooms(id),
    wanted_start TIMESTAMPTZ NOT NULL,
    wanted_end TIMESTAMPTZ NOT NULL,
    party_size INTEGER NOT NULL,
    joined_at TIMESTAMPTZ DEFAULT NOW(),
    status VARCHAR(20) NOT NULL DEFAULT 'waiting'
        CHECK (status IN (
            'waiting', 'offered', 'fulfilled',
            'cancelled', 'expired'
        )),
    CHECK (wanted_end > wanted_start),
    CHECK (party_size > 0)
);

-- F. WAITING LIST OFFERS
CREATE TABLE waiting_list_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    waiting_list_entry_id BIGINT NOT NULL
        REFERENCES waiting_list_entries(id),
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    offered_at TIMESTAMPTZ DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending', 'accepted', 'declined', 'expired'
        ))
);

-- G. BOOKING EXTENSIONS
CREATE TABLE booking_extensions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    requested_end_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    requested_at TIMESTAMPTZ DEFAULT NOW()
);

-- H. ISSUE REPORTS
CREATE TABLE issue_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    issue_category VARCHAR(100) NOT NULL,
    description TEXT,
    image_path TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'submitted'
        CHECK (status IN (
            'submitted', 'in_progress', 'resolved'
        )),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- I. AI REPORT SUMMARIES
CREATE TABLE ai_report_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    summary_text TEXT,
    issue_counts JSONB,
    recurring_issues JSONB,
    suggested_actions JSONB,
    generated_at TIMESTAMPTZ DEFAULT NOW(),
    CHECK (period_end >= period_start)
);

-- J. NOTIFICATIONS
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    message_type VARCHAR(50) NOT NULL,
    message TEXT NOT NULL,
    scheduled_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    is_read BOOLEAN DEFAULT FALSE,
    status VARCHAR(20) DEFAULT 'pending'
        CHECK (status IN (
            'pending', 'sent', 'failed'
        )),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

