-- I2. AI ANALYSIS OF EACH ISSUE REPORT
CREATE TABLE issue_report_analyses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_report_id BIGINT NOT NULL UNIQUE REFERENCES issue_reports(id) ON DELETE CASCADE,
    state VARCHAR(20) NOT NULL
        CHECK (state IN ('auto_accepted', 'needs_review', 'staff_reviewed')),
    review_reason VARCHAR(30)
        CHECK (review_reason IN ('ai_error', 'invalid_output', 'low_confidence')),
    ai_category VARCHAR(100),
    ai_severity VARCHAR(10),
    ai_summary TEXT,
    ai_confidence NUMERIC(4,3),
    ai_raw_output TEXT,
    final_category VARCHAR(100),
    final_severity VARCHAR(10),
    final_summary TEXT,
    reviewed_by BIGINT REFERENCES users(id),
    reviewed_at TIMESTAMPTZ,
    review_note TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);